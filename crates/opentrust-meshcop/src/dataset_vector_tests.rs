//! Vectors of OpenThread `tests/unit/test_dataset.cpp`.

use opentrust_core::types::NetworkKey;

use crate::dataset::{Dataset, DatasetType};
use crate::tlv::{PAGE0_CHANNELS, SecurityPolicy, ty};

#[test]
fn ot_test_dataset_vector() {
    const TLVS: [u8; 106] = [
        0x0e, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x0f,
        0x35, 0x06, 0x00, 0x04, 0x00, 0x1f, 0xff, 0xe0, 0x02, 0x08, 0x1d, 0xe5, 0xbf, 0xec, 0xd5,
        0x16, 0x5b, 0x8f, 0x07, 0x08, 0xfd, 0xe2, 0x1f, 0x0c, 0x8a, 0x13, 0xe8, 0xe7, 0x05, 0x10,
        0xea, 0xf9, 0x14, 0x9f, 0xdc, 0x73, 0x78, 0x77, 0x06, 0x98, 0xd5, 0x91, 0x80, 0x22, 0x19,
        0x58, 0x03, 0x0f, 0x4f, 0x70, 0x65, 0x6e, 0x54, 0x68, 0x72, 0x65, 0x61, 0x64, 0x2d, 0x61,
        0x61, 0x63, 0x33, 0x01, 0x02, 0xfa, 0xce, 0x04, 0x10, 0x2e, 0xaa, 0xe2, 0x94, 0x84, 0x38,
        0x8e, 0x31, 0x19, 0x58, 0x1a, 0x7b, 0x5a, 0x94, 0x8c, 0x07, 0x0c, 0x04, 0x02, 0xa0, 0xf7,
        0xf8,
    ];
    let d = Dataset::from_tlvs(&TLVS[..]).unwrap();
    for t in [
        ty::CHANNEL,
        ty::PAN_ID,
        ty::EXT_PAN_ID,
        ty::NETWORK_NAME,
        ty::PSKC,
        ty::NETWORK_KEY,
        ty::MESH_LOCAL_PREFIX,
        ty::SECURITY_POLICY,
        ty::ACTIVE_TIMESTAMP,
    ] {
        assert!(d.contains(t));
    }
    let tl = d.tlvs();
    assert_eq!(tl.pan_id().unwrap(), 0xface);
    assert_eq!(tl.channel().unwrap().channel, 15);
    assert_eq!(tl.network_name().unwrap().as_str(), "OpenThread-aac3");
    assert_eq!(tl.channel_mask().unwrap(), PAGE0_CHANNELS);
    assert_eq!(tl.network_key().unwrap().0[0], 0xea);
    assert_eq!(tl.active_timestamp().unwrap().seconds, 1);
    assert_eq!(tl.security_policy().unwrap(), SecurityPolicy::default());
    assert!(d.contains_all_required_for(DatasetType::Active));

    // Replace the network key and PAN ID.
    let mut d2 = d.clone();
    d2.set_network_key(&NetworkKey([
        0, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
    ]))
    .unwrap();
    d2.set_pan_id(0xface).unwrap();
    assert_eq!(d2.len(), d.len());
    assert!(!d.is_subset_of(&d2));

    // Duplicate Channel TLVs are invalid.
    let dup = [0x00, 0x03, 0x00, 0x00, 0x1a, 0x00, 0x03, 0x00, 0x00, 0x1a];
    assert!(Dataset::from_tlvs(&dup).is_err());
}
