#[test]
fn round_one_rejects_bad_zkp() {
    let (x, v, r, _) = kkp_fields(&CLI_ONE, 0);
    // Corrupted r.
    let mut m = CLI_ONE.to_vec();
    m[r.end - 1] ^= 1;
    assert_eq!(srv_read_one(&m), Err(Error::Security));
    // V replaced by another valid point (X itself).
    let mut m = CLI_ONE.to_vec();
    m.copy_within(x, v.start);
    assert_eq!(srv_read_one(&m), Err(Error::Security));
    // Corrupted r of the second KKP.
    let mut m = CLI_ONE.to_vec();
    let last = m.len() - 1;
    m[last] ^= 0x80;
    assert_eq!(srv_read_one(&m), Err(Error::Security));
}

