type Range = core::ops::Range<usize>;

/// Byte ranges of the fields of one `ECJPAKEKeyKP` starting at `off`:
/// (X, V, r, end).
fn kkp_fields(m: &[u8], off: usize) -> (Range, Range, Range, usize) {
    assert_eq!(m[off], 65);
    let x = off + 1..off + 66;
    assert_eq!(m[off + 66], 65);
    let v = off + 67..off + 132;
    let rlen = m[off + 132] as usize;
    let r = off + 133..off + 133 + rlen;
    let end = r.end;
    (x, v, r, end)
}

/// mbedTLS self-test #2 ("reference handshake"): both sides read the
/// reference messages and derive the reference PMS and shared key.
#[test]
fn mbedtls_reference_handshake() {
    let (mut cli, mut srv) = loaded();
    srv.read_round_one(&C, &CLI_ONE).unwrap();
    cli.read_round_one(&C, &SRV_ONE).unwrap();
    cli.read_round_two(&C, &SRV_TWO).unwrap();
    srv.read_round_two(&C, &CLI_TWO).unwrap();

    assert_eq!(srv.derive_secret(&C).unwrap(), PMS);
    assert_eq!(srv.shared_key().unwrap(), SHARED_KEY);
    assert_eq!(cli.derive_secret(&C).unwrap(), PMS);
    assert_eq!(cli.shared_key().unwrap(), SHARED_KEY);
}

/// The public keys in the reference round-one messages are `x_i * G` for
/// the reference private keys (scalar multiplication and point encoding
/// against mbedTLS).
#[test]
fn mbedtls_reference_public_keys() {
    let c = SoftP256;
    for (msg, k1, k2) in [(&CLI_ONE[..], &X1, &X2), (&SRV_ONE[..], &X3, &X4)] {
        let (x, _, _, end) = kkp_fields(msg, 0);
        let (x2, _, _, end2) = kkp_fields(msg, end);
        assert_eq!(end2, msg.len());
        let p1 = c
            .encode(&c.mul_base(&c.scalar_from_be(k1).unwrap()))
            .unwrap();
        let p2 = c
            .encode(&c.mul_base(&c.scalar_from_be(k2).unwrap()))
            .unwrap();
        assert_eq!(&msg[x], &p1[..]);
        assert_eq!(&msg[x2], &p2[..]);
    }
}

/// Round two written with the reference keys carries the reference public
/// key `Xm` (only the ZKP is random); the server message starts with the
/// curve parameters; both verify on the reference peer and yield the
/// reference PMS.
#[test]
fn mbedtls_reference_round_two_written() {
    let (mut cli, mut srv) = loaded();
    srv.read_round_one(&C, &CLI_ONE).unwrap();
    cli.read_round_one(&C, &SRV_ONE).unwrap();
    let mut rng = Lgc::new();

    let mut buf = [0u8; ROUND_TWO_MAX_LEN];
    let n = srv.write_round_two(&C, &mut rng, &mut buf).unwrap();
    assert_eq!(&buf[..3 + 66], &SRV_TWO[..3 + 66]);
    cli.read_round_two(&C, &buf[..n]).unwrap();

    let n = cli.write_round_two(&C, &mut rng, &mut buf).unwrap();
    assert_eq!(&buf[..66], &CLI_TWO[..66]);
    srv.read_round_two(&C, &buf[..n]).unwrap();
    assert_eq!(srv.derive_secret(&C).unwrap(), PMS);
    assert_eq!(cli.derive_secret(&C).unwrap(), PMS);
}

